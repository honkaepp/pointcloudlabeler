//! The operation reference as Markdown, generated from the catalogue.
//!
//! `docs/OPERATIONS.md` in the repository is this text; `pointcloudlabeler
//! ops docs` prints it, and a test fails when the committed file drifts
//! from the catalogue — so the reference is never stale, and never
//! written by hand.

use std::fmt::Write;

use super::schema::{self, Kind};
use crate::ops;

pub fn operations_markdown() -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# Operation reference");
    let _ = writeln!(out);
    let _ = writeln!(out, "<!-- Generated by `pointcloudlabeler ops docs` from the operation catalogue (src-tauri/src/ops). Do not edit; regenerate. -->");
    let _ = writeln!(out);
    let _ = writeln!(out, "Every operation PointCloudLabeler can run without its window, as the command line, the console interface, the HTTP API and the MCP server offer it. The same operations drive the desktop application's panels; the defaults are the panels' defaults.");
    let _ = writeln!(out);
    let _ = writeln!(out, "| Surface | How an operation is named |");
    let _ = writeln!(out, "| --- | --- |");
    let _ = writeln!(out, "| Command line | `pointcloudlabeler <group> <name>`, parameters as `--kebab-case` flags, or `pointcloudlabeler ops run <group.name> --params '{{…}}'` |");
    let _ = writeln!(out, "| HTTP API | `POST /api/ops/<group.name>` with the parameters as the JSON body |");
    let _ = writeln!(out, "| MCP | the tool `<group>_<name>` with the parameters as its arguments |");
    let _ = writeln!(out, "| Recipe | `{{\"op\": \"<group.name>\", \"params\": {{…}}}}` |");
    let _ = writeln!(out);
    let _ = writeln!(out, "Parameter names are the wire names (camelCase) the desktop application uses too. A parameter marked *required* has no default. *Writes* means the operation changes the dataset or project it names; *stage* is what `run cancel` takes to stop it.");
    let mut group: Option<ops::Group> = None;
    for op in ops::catalogue() {
        if group != Some(op.group) {
            group = Some(op.group);
            let _ = writeln!(out);
            let _ = writeln!(out, "## {}", op.group.as_str());
        }
        let _ = writeln!(out);
        let _ = writeln!(out, "### `{}`", op.name);
        let _ = writeln!(out);
        let _ = writeln!(out, "{}", op.summary);
        let _ = writeln!(out);
        let mut facts = Vec::new();
        facts.push(if op.mutates { "writes".to_string() } else { "read-only".to_string() });
        if let Some(stage) = op.stage {
            facts.push(format!("stage `{stage}`"));
        }
        let (g, leaf) = op.name.split_once('.').unwrap_or((op.name, ""));
        facts.push(format!("command line `pointcloudlabeler {g} {}`", schema::flag_name(leaf)));
        facts.push(format!("MCP tool `{}`", schema::tool_name(op.name)));
        let _ = writeln!(out, "{}.", facts.join(" · "));
        let params = schema::params_of(&op.params_schema());
        if params.is_empty() {
            let _ = writeln!(out);
            let _ = writeln!(out, "No parameters.");
            continue;
        }
        let _ = writeln!(out);
        let _ = writeln!(out, "| Parameter | Type | Default | Description |");
        let _ = writeln!(out, "| --- | --- | --- | --- |");
        for p in params {
            let kind = match p.kind {
                Kind::String => "string",
                Kind::Number => "number",
                Kind::Integer => "integer",
                Kind::Boolean => "boolean",
                Kind::Json => "JSON",
            };
            let kind = if p.nullable { format!("{kind}, nullable") } else { kind.to_string() };
            let default = match (&p.default, p.required) {
                (Some(d), _) => format!("`{}`", schema::default_text(d).replace('|', "\\|")),
                (None, true) => "*required*".to_string(),
                (None, false) => "—".to_string(),
            };
            let mut desc = p.description.replace('\n', " ").replace('|', "\\|");
            if !p.choices.is_empty() {
                let _ = write!(desc, " One of: {}.", p.choices.iter().map(|c| format!("`{c}`")).collect::<Vec<_>>().join(", "));
            }
            let _ = writeln!(out, "| `{}` | {kind} | {default} | {desc} |", p.name);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_reference_covers_every_operation_and_parameter() {
        let md = operations_markdown();
        for op in ops::catalogue() {
            assert!(md.contains(&format!("### `{}`", op.name)), "{} missing", op.name);
            for p in schema::params_of(&op.params_schema()) {
                assert!(md.contains(&format!("| `{}` |", p.name)), "{}.{} missing", op.name, p.name);
            }
        }
        assert!(md.contains("### `segment.chm`"));
        assert!(md.contains("`pointcloudlabeler dataset realign-to-source`"));
        assert!(md.contains("MCP tool `dataset_realign_to_source`"));
    }

    /// docs/OPERATIONS.md is this text. Regenerate it with
    /// `pointcloudlabeler ops docs > docs/OPERATIONS.md` (from the
    /// headless binary) when the catalogue changes.
    #[test]
    fn the_committed_reference_is_current() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../docs/OPERATIONS.md");
        let committed = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let generated = operations_markdown();
        if committed != generated {
            // Point at the first differing line rather than dumping both.
            let mismatch = committed.lines().zip(generated.lines()).enumerate().find(|(_, (a, b))| a != b);
            match mismatch {
                Some((i, (a, b))) => panic!("docs/OPERATIONS.md is stale at line {}:\n  committed: {a}\n  generated: {b}\nregenerate with `pointcloudlabeler ops docs > docs/OPERATIONS.md`", i + 1),
                None => panic!("docs/OPERATIONS.md is stale (length {} vs {}); regenerate with `pointcloudlabeler ops docs > docs/OPERATIONS.md`", committed.len(), generated.len()),
            }
        }
    }
}
